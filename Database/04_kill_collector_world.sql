-- Kill Collector: definitions and targets. Apply to the WORLD database.
-- Per-character progress is a separate file, 05_kill_collector_characters.sql,
-- which must be applied to the CHARACTERS database.
--
-- Collector -> quest/target/cap/XP data comes from Return of Reckoning's public
-- GraphQL API (production-api.waremu.com), which serves the live collector quests.
-- Target creature entries are NOT available from that API - it returns only a
-- human-readable label - so entries were resolved against creature_protos,
-- scoped to the zones each collector actually spawns in.
--
--   109 collectors resolved automatically by zone-scoped name match
--    20 hand-mapped where the label names a camp or faction rather than a mob
--     3 left unmapped: no matching creature exists in ProjectWAR's world data
--
-- Unmapped collectors are seeded with a definition but no target rows. They are
-- inert at runtime (no kill can credit them) and are listed at the end of this
-- file so they can be filled in later without a code change.
--
-- Caps here are current RoR values (20-60 by chapter). Retail is documented as
-- 60 for all collectors; KillCap is per-collector data precisely so that choice
-- stays configurable rather than compiled in.
--
-- IMPORTANT: column order below must match the property order in the
-- Kill_Collector_Definition / Kill_Collector_Target DataObjects. FrameWork binds
-- query results to properties by ordinal position, not by name.

DROP TABLE IF EXISTS `kill_collector_targets`;
DROP TABLE IF EXISTS `kill_collector_definitions`;

CREATE TABLE `kill_collector_definitions` (
  `CollectorEntry`   int unsigned      NOT NULL,
  `KillCap`          smallint unsigned NOT NULL DEFAULT 60,
  `Xp`               int unsigned      NOT NULL DEFAULT 0,
  `CompletionTokEntry` smallint unsigned NOT NULL DEFAULT 0,
  `TargetLabel`      varchar(128)      NOT NULL DEFAULT '',
  PRIMARY KEY (`CollectorEntry`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE `kill_collector_targets` (
  `CollectorEntry`   int unsigned NOT NULL,
  `CreatureEntry`    int unsigned NOT NULL,
  PRIMARY KEY (`CollectorEntry`,`CreatureEntry`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

