-- 09_conform_ability_targeting_and_ranges_to_client.sql
--
-- Gives both ability tables the client's TargetType, and sets 2122 ability ranges to the client's.
--
-- POLICY. The 1.4.8 client is the arbiter; where it holds a value, ours conforms, and where the server
-- reads the same field differently, the server changes.
--
-- WHY THE TWO GO TOGETHER. The emulator decided whether a cast lands on its caster from Range: 0 meant
-- the caster (AbilityProcessor.GetTarget). The live server decided it from the client's TargetType, and
-- the packet captures show it. Across the 1,027 logs, abilities the client marks TargetType 0 or 3 were
-- cast on their caster (772 of 773), and TargetType 1 abilities on another unit (844 of
-- 844) -- 163 of those with a client range of 0. The client's own tooltip calls a zero range "Self"
-- (LABEL_ABILITY_TOOLTIP_NO_RANGE), but a zero range did not make the live server target the caster.
--
-- So the ranges could not be taken while Range still chose the target: 1941 abilities would have
-- stopped casting on themselves and 115 started. The server now decides by TargetType
-- (AbilityInfo.TargetsCaster), and a range of 0 on an ability that needs a target sets no limit of its
-- own, which is how creature AI already reads it (ABrain.cs).
--
-- WHAT CHANGES IN PLAY. Of the abilities that have commands, 131 now land on a different unit than
-- before. The captures saw 55 of them: 54 land as the live server's did, and 1 does not
-- (5238 Whirl an' Twirl), where the client's TargetType is followed over the capture.
--
-- TARGETTYPE is copied from data/bin/abilityexport.bin for the 5864 rows the client has a record of, and
-- stays NULL on the rest, which keep the emulator's older reading of a zero range. 0 and 3 cast on the
-- caster, 1 needs an enemy, 2 an ally, 5 the career target, 6 a point on the ground.
--
-- RANGES. The client holds range at twelve units to the foot and Range is feet (the crosswalk's rule).
-- 574 client ranges are not whole feet and round to the nearest foot: the server measures
-- distance in whole feet (GetDistanceToObject), so a fraction of a foot is not a distance it can check.
-- AIRange, the server-only distance creature AI casts from, is lowered to the new range on the 15
-- rows where it would exceed it, so a creature does not try to cast from where the cast must fail.
--
-- Both tables are written (CLAUDE.md hard rule 1), each with its own old value.
--
-- ORDER. The server build that reads TargetType maps the column, so apply this before starting it.
-- Safe to re-run: the columns are added only if missing, TargetType is set to a fixed value, and each
-- range UPDATE matches only the old value. Ability data is cached at boot, so restart the server.

USE war_world;

SET @missing := (SELECT COUNT(*) = 0 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
    AND TABLE_NAME = 'mythic_src_abilities' AND COLUMN_NAME = 'TargetType');
SET @ddl := IF(@missing, 'ALTER TABLE mythic_src_abilities ADD COLUMN TargetType TINYINT UNSIGNED NULL AFTER `Range`', 'DO 0');
PREPARE ddl FROM @ddl;
EXECUTE ddl;
DEALLOCATE PREPARE ddl;

SET @missing := (SELECT COUNT(*) = 0 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
    AND TABLE_NAME = 'abilities' AND COLUMN_NAME = 'TargetType');
