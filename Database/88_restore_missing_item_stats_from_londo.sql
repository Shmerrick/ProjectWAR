--
--   108  PURE OMISSION -- every pair we carry also appears in Londo's set, he simply has more.
--        Our block is a subset of his. Topping it up cannot contradict anything we already assert.
--        These are migrated.
--
--    91  VALUE CONFLICT -- we carry a pair Londo does not, at a different stat or a different
--        value. Item 30984 has Initiative 9 where Londo has WeaponSkill 9: the same number against
--        a different stat id, so one of the two is simply wrong and no rule decides which.
--        These are NOT migrated. They are listed in
--        docs/data-matrix/crosswalk/item-stat-conflicts.csv for individual review, and tracked as
--        BUG-153.
--
-- The pattern in the 108 is consistent and looks like an import truncation rather than drift: our
-- pairs are a prefix of Londo's and the missing entry is almost always the last one. 27775
-- Goldfist Breastscale had Toughness 10 and Wounds 4 but not Initiative 2; 28059 Priesterstadt
-- Gorget had Strength 14 and Willpower 22 but not Wounds 12.
--
-- Existing pairs keep their order and their values -- only the missing entries are appended, then
-- the block is padded back to twelve slots the way the rest of the table is written. No item ends
-- up with more than twelve.
--
-- Both tables are written; `UseMythicActionCoverageTables` ships true. Item data is cached at boot,
-- so a restart is required. NEEDS IN-CLIENT TESTING: this makes 108 items measurably stronger.

