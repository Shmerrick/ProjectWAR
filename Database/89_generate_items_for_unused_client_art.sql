-- 89_generate_items_for_unused_client_art.sql
--
-- Creates 2,121 items so that client art with no item behind it can be spawned, worn and looked at.
--
-- READ THIS FIRST: THESE ARE NOT RESTORED 1.4.8 CONTENT.
--
-- Every other item migration in this series is gated on a source *naming* the thing -- migration 87
-- required both a Londo row and a live packet capture before adding 95 items, and deliberately left
-- ~1,850 orphaned models alone on the grounds that art existing is not evidence an item existed.
-- That reasoning has not changed and still governs restoration work.
--
-- This migration has a different purpose, asked for explicitly: make the unused art *usable*, so
-- models that exist can be put on a character and inspected. The items below are manufactured. They
-- are named after the art they display and every one carries a Description saying so, so nothing
-- here can be mistaken later for recovered content.
--
-- WHAT IS CREATED
--
--   2,121 items, entries 46481-48601, from `data/gamedata/objects.csv` rows that have no item, are
--   named, are not `WORLD OBJ` scenery or Test/CCTest/placeholder/not-used, and resolve to an icon
--   so they display in a bag. NPC-only art is deliberately included -- it was excluded from the
--   restoration work because NPC art is not player content, which is irrelevant here.
--
--   1,444 have an equip slot inferred from the art name (shoulders 295, helm 289, body 199, belt
--   144, either-hand 171, gloves 101, boots 87, main hand 61, off hand 33, back 33, ranged 31).
--   677 are props and `INV OBJ` inventory pieces with no slot -- juggling clubs, bottles, torch and
--   halberd templates, carried crates. They are still items with an icon; they simply cannot be
--   worn, which is correct for what they are.
--
-- WHY THE ENTRY RANGE IS 46481. Item entries are a server-side handle. The client is sent the value
-- but never looks it up, so any unused id works and the gaps in the low range are free to use.
-- 46481-53379 is the first contiguous run of that size, verified empty in `item_infos`,
-- `mythic_src_item_infos`, `characters_items`, `vendor_items`, `pquest_loot` and `loot_groups`.
--
-- WHY THEY EQUIP ON ANYONE. `Type` is 0, which `ItemsInterface.CanUseItemTypeForCareer` treats as
-- "no type restriction" (it returns true early for Type 0). `Career`, `Race`, `MinRank` and
-- `MinRenown` are 0, and each of those gates only when non-zero. So the only thing that decides
-- where an item goes is its SlotId.
--
-- No stats, no set, no bind, sell price 0. These are for looking at art, not for playing with.
--
-- TO REMOVE THEM: DELETE FROM item_infos WHERE Entry BETWEEN 46481 AND 48601; and the same for
-- mythic_src_item_infos. Nothing else references them.
--
-- Both tables are written; `UseMythicActionCoverageTables` ships true. Item data is cached at boot.

